export type SupportedLanguage = 'en' | 'ar' | 'af' | 'zh' | 'cs' | 'nl' | 'fr';

export const SUPPORTED_LANGUAGES: SupportedLanguage[] = [
  'en',
  'ar',
  'af',
  'zh',
  'cs',
  'nl',
  'fr',
];

export const RTL_LANGUAGES: ReadonlySet<SupportedLanguage> = new Set(['ar']);

export function normalizeLanguage(code?: string | null): SupportedLanguage {
  const clean = (code || '').trim().toLowerCase();
  if ((SUPPORTED_LANGUAGES as string[]).includes(clean)) {
    return clean as SupportedLanguage;
  }
  return 'en';
}

export function isLanguageRTL(code?: string | null): boolean {
  return RTL_LANGUAGES.has(normalizeLanguage(code));
}

